use anyhow::Result;
use nocode_model::{DatabaseDriver, Project, RelationType};

use crate::view;

#[derive(Debug)]
pub struct MigrationFile {
    pub version: String,
    pub name: String,
    pub up_sql: String,
    pub down_sql: String,
}

#[derive(Debug, Default)]
pub struct DatabaseOutput {
    pub migrations: Vec<MigrationFile>,
    pub schema_sql: String,
}

/// A referential constraint derived from an entity relation.
#[derive(Debug)]
struct ForeignKey {
    table: String,
    column: String,
    referenced_table: String,
    referenced_column: String,
    on_delete: &'static str,
    on_update: &'static str,
}

/// Render a `nocode_model` referential action as its SQL keyword.
fn sql_action(action: &str) -> &'static str {
    match action {
        "Cascade" => "CASCADE",
        "SetNull" => "SET NULL",
        "Restrict" => "RESTRICT",
        "NoAction" => "NO ACTION",
        "SetDefault" => "SET DEFAULT",
        _ => "NO ACTION",
    }
}

/// Keep only characters that are safe in a bare SQL identifier.
fn sanitize_ident(input: &str) -> String {
    input
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || c == '_' {
                c
            } else {
                '_'
            }
        })
        .collect()
}

/// Collect every foreign key implied by the project's entity relations.
///
/// A relation only becomes a constraint when both endpoints resolve to a real
/// field, so relations pointing at a deleted entity or field are skipped rather
/// than emitting a statement that would fail to apply.
fn foreign_keys(project: &Project) -> Vec<ForeignKey> {
    let mut keys = Vec::new();
    for entity in project.entities.values() {
        let table = entity
            .options
            .table_name
            .clone()
            .unwrap_or_else(|| view::snake(&entity.plural_name));
        for relation in &entity.relations {
            // A many-to-many relation needs a generated join table, which the
            // generator does not emit yet. Emitting a direct foreign key would
            // be wrong, so it is skipped until join tables exist.
            if matches!(relation.relation_type, RelationType::ManyToMany { .. }) {
                continue;
            }
            let Some(from_field) = entity.fields.iter().find(|f| f.id == relation.from_field)
            else {
                continue;
            };
            let Some(target) = project.entities.get(&relation.to_entity) else {
                continue;
            };
            let Some(to_field) = target.fields.iter().find(|f| f.id == relation.to_field) else {
                continue;
            };
            let referenced_table = target
                .options
                .table_name
                .clone()
                .unwrap_or_else(|| view::snake(&target.plural_name));
            keys.push(ForeignKey {
                table: table.clone(),
                column: view::snake(&from_field.name),
                referenced_table,
                referenced_column: view::snake(&to_field.name),
                on_delete: sql_action(&format!("{:?}", relation.on_delete)),
                on_update: sql_action(&format!("{:?}", relation.on_update)),
            });
        }
    }
    keys
}

/// Generate the schema SQL for a project using the driver-specific types and
/// quoting rules. Emits entity tables, their indexes and the foreign keys
/// implied by entity relations.
pub fn generate_schema_sql(project: &Project, driver: DatabaseDriver) -> Result<String> {
    let entities = view::entities_view(project, &driver);
    let keys = foreign_keys(project);
    let mut sql = String::new();
    sql.push_str(&format!(
        "-- Database schema for {}\n-- Generated by No-Code IDE\n\n",
        project.name
    ));

    // SQLite has no `ALTER TABLE ... ADD CONSTRAINT`, so its foreign keys must
    // be declared while the table is created. Postgres and MySQL add them once
    // every table exists, which also covers forward and self references.
    let inline_keys = matches!(driver, DatabaseDriver::SQLite);

    for entity in &entities {
        let table = entity
            .get("table")
            .and_then(|v| v.as_str())
            .unwrap_or("entity")
            .to_string();

        let empty = Vec::new();
        let fields = entity
            .get("fields")
            .and_then(|v| v.as_array())
            .unwrap_or(&empty);

        let mut lines: Vec<String> = Vec::new();

        for field in fields {
            let column = field
                .get("column")
                .and_then(|v| v.as_str())
                .unwrap_or("col");
            let sql_type = field
                .get("sql_type")
                .and_then(|v| v.as_str())
                .unwrap_or("TEXT");
            let is_pk = field
                .get("is_primary_key")
                .and_then(|v| v.as_bool())
                .unwrap_or(false);
            let is_integer = field
                .get("is_integer")
                .and_then(|v| v.as_bool())
                .unwrap_or(false);
            let not_null = field
                .get("not_null")
                .and_then(|v| v.as_bool())
                .unwrap_or(false);
            let unique = field
                .get("is_unique")
                .and_then(|v| v.as_bool())
                .unwrap_or(false);
            let default_value = field
                .get("default_value")
                .and_then(|v| v.as_str())
                .unwrap_or("");

            let mut line = format!("    {} {}", column, sql_type);

            if is_pk {
                if is_integer {
                    match driver {
                        DatabaseDriver::Postgres => line = format!("    {} SERIAL", column),
                        DatabaseDriver::MySQL => {
                            line = format!("    {} INTEGER AUTO_INCREMENT", column)
                        }
                        _ => line = format!("    {} INTEGER", column),
                    }
                }
                line.push_str(" PRIMARY KEY");
            }
            if not_null {
                line.push_str(" NOT NULL");
            }
            if unique && !is_pk {
                line.push_str(" UNIQUE");
            }
            if !default_value.is_empty() {
                line.push_str(&format!(" DEFAULT {}", default_value));
            }

            lines.push(line);
        }

        if inline_keys {
            for key in keys.iter().filter(|k| k.table == table) {
                lines.push(format!(
                    "    FOREIGN KEY ({}) REFERENCES {} ({}) ON DELETE {} ON UPDATE {}",
                    key.column,
                    key.referenced_table,
                    key.referenced_column,
                    key.on_delete,
                    key.on_update
                ));
            }
        }

        sql.push_str(&format!("CREATE TABLE IF NOT EXISTS {} (\n", table));
        sql.push_str(&lines.join(",\n"));
        sql.push_str("\n);\n\n");

        if let Some(indexes) = entity.get("indexes").and_then(|v| v.as_array()) {
            for idx in indexes {
                let name = idx.get("name").and_then(|v| v.as_str()).unwrap_or("idx");
                let columns = idx.get("columns").and_then(|v| v.as_str()).unwrap_or("");
                if columns.is_empty() {
                    continue;
                }
                sql.push_str(&format!(
                    "CREATE INDEX IF NOT EXISTS {}_idx ON {} ({});\n",
                    name, table, columns
                ));
            }
            sql.push('\n');
        }
    }

    if !inline_keys {
        for key in &keys {
            sql.push_str(&format!(
                "ALTER TABLE {} ADD CONSTRAINT {} FOREIGN KEY ({}) REFERENCES {} ({}) ON DELETE {} ON UPDATE {};\n",
                key.table,
                sanitize_ident(&format!("fk_{}_{}", key.table, key.column)),
                key.column,
                key.referenced_table,
                key.referenced_column,
                key.on_delete,
                key.on_update
            ));
        }
        sql.push('\n');
    }

    Ok(sql)
}

pub async fn generate_database(
    project: &Project,
    _output_dir: &std::path::Path,
) -> Result<DatabaseOutput> {
    let driver = project.settings.database.driver.clone();
    let schema_sql = generate_schema_sql(project, driver)?;

    let mut output = DatabaseOutput {
        migrations: Vec::new(),
        schema_sql: schema_sql.clone(),
    };

    let down_sql = {
        let mut down = String::from("-- Down migration\n\n");
        for entity in project.entities.values().rev() {
            let table = entity
                .options
                .table_name
                .clone()
                .unwrap_or_else(|| view::snake(&entity.plural_name));
            down.push_str(&format!("DROP TABLE IF EXISTS {};\n", table));
        }
        down
    };

    output.migrations.push(MigrationFile {
        version: "0001".to_string(),
        name: "initial_schema".to_string(),
        up_sql: schema_sql,
        down_sql,
    });

    Ok(output)
}
