//! Framework-agnostic project service shared by the desktop (Tauri) and web shells.

use std::path::PathBuf;
use std::sync::Mutex;

use nocode_model::entity::{EntityField, EntityFieldType, FieldId};
use nocode_model::{DatabaseDriver, Entity, FrontendFramework, Project};

/// Serialized summary of a completed code-generation run.
#[derive(Debug, Clone, serde::Serialize)]
pub struct GenerationReport {
    pub output_dir: String,
    pub backend_files: usize,
    pub frontend_files: usize,
    pub migrations: usize,
}

/// Serialize a project to pretty JSON.
pub fn project_json(project: &Project) -> Result<String, String> {
    serde_json::to_string_pretty(project).map_err(|e| e.to_string())
}

fn uuid_pk(name: &str, order: usize) -> EntityField {
    EntityField {
        id: FieldId::new(),
        name: name.to_string(),
        field_type: EntityFieldType::Uuid,
        nullable: false,
        unique: true,
        default: None,
        auto_generate: None,
        validation: None,
        comment: Some("Primary key".to_string()),
        order,
    }
}

fn field(name: &str, field_type: EntityFieldType, nullable: bool, order: usize) -> EntityField {
    EntityField {
        id: FieldId::new(),
        name: name.to_string(),
        field_type,
        nullable,
        unique: false,
        default: None,
        auto_generate: None,
        validation: None,
        comment: None,
        order,
    }
}

/// Build a small, fully-formed project so the IDE opens with content.
pub fn build_sample_project() -> Project {
    let mut project = Project::new("Sample Commerce");
    project.description = Some("A demo storefront generated by the No-Code IDE.".to_string());

    let mut customer = Entity::new("Customer");
    customer.fields = vec![
        uuid_pk("id", 0),
        field(
            "name",
            EntityFieldType::String {
                max_length: Some(120),
            },
            false,
            1,
        ),
        field(
            "email",
            EntityFieldType::String {
                max_length: Some(255),
            },
            false,
            2,
        ),
    ];
    project.entities.insert(customer.id.clone(), customer);

    let mut product = Entity::new("Product");
    product.fields = vec![
        uuid_pk("id", 0),
        field(
            "name",
            EntityFieldType::String {
                max_length: Some(120),
            },
            false,
            1,
        ),
        field(
            "price",
            EntityFieldType::Decimal {
                precision: 10,
                scale: 2,
            },
            true,
            2,
        ),
        field("in_stock", EntityFieldType::Boolean, false, 3),
    ];
    project.entities.insert(product.id.clone(), product);

    let mut order = Entity::new("Order");
    order.fields = vec![
        uuid_pk("id", 0),
        field("customer_id", EntityFieldType::Uuid, false, 1),
        field("quantity", EntityFieldType::Integer, false, 2),
        field(
            "total",
            EntityFieldType::Decimal {
                precision: 12,
                scale: 2,
            },
            false,
            3,
        ),
    ];
    project.entities.insert(order.id.clone(), order);

    // Default to a zero-config SQLite database so generation runs out of the box.
    project.settings.database.driver = DatabaseDriver::SQLite;
    project.settings.database.url = "sqlite://sample.db?mode=rwc".to_string();

    project
}

/// Holds the currently open project for any front-end shell.
#[derive(Debug, Default)]
pub struct IdeService {
    current_project: Mutex<Option<Project>>,
    project_path: Mutex<Option<PathBuf>>,
}

impl IdeService {
    pub fn new() -> Self {
        Self::default()
    }

    fn current_project_clone(&self) -> Option<Project> {
        self.current_project.lock().unwrap().clone()
    }

    fn set_current_project(&self, project: Option<Project>) {
        *self.current_project.lock().unwrap() = project;
    }

    pub fn new_project(&self, name: &str) -> Result<String, String> {
        let project = Project::new(name);
        let json = project_json(&project)?;
        self.set_current_project(Some(project));
        Ok(json)
    }

    pub fn seed_sample_project(&self) -> Result<String, String> {
        let project = build_sample_project();
        let json = project_json(&project)?;
        self.set_current_project(Some(project));
        Ok(json)
    }

    pub fn set_db_driver(&self, driver: &str) -> Result<String, String> {
        let parsed = match driver {
            "postgres" => DatabaseDriver::Postgres,
            "sqlite" => DatabaseDriver::SQLite,
            "mysql" => DatabaseDriver::MySQL,
            "sql_server" => DatabaseDriver::SqlServer,
            "oracle" => DatabaseDriver::Oracle,
            other => return Err(format!("unknown database driver: {other}")),
        };

        let mut guard = self.current_project.lock().unwrap();
        let project = guard.as_mut().ok_or("No project loaded")?;
        project.settings.database.driver = parsed;
        if project.settings.database.url.trim().is_empty() {
            project.settings.database.url = match &project.settings.database.driver {
                DatabaseDriver::SQLite => "sqlite://sample.db?mode=rwc".to_string(),
                DatabaseDriver::Postgres => {
                    "postgres://postgres:postgres@localhost:5432/app".to_string()
                }
                _ => String::new(),
            };
        }
        project_json(project)
    }

    pub fn set_frontend_framework(&self, framework: &str) -> Result<String, String> {
        let parsed = match framework {
            "leptos" => FrontendFramework::Leptos,
            other => return Err(format!("unknown frontend framework: {other}")),
        };

        let mut guard = self.current_project.lock().unwrap();
        let project = guard.as_mut().ok_or("No project loaded")?;
        project.settings.frontend.framework = parsed;
        project_json(project)
    }

    pub fn save_project(&self, path: &str) -> Result<(), String> {
        let project = self.current_project_clone().ok_or("No project loaded")?;

        let json = serde_json::to_string_pretty(&project).map_err(|e| e.to_string())?;
        std::fs::write(path, json).map_err(|e| e.to_string())?;

        *self.project_path.lock().unwrap() = Some(PathBuf::from(path));
        Ok(())
    }

    pub fn load_project(&self, path: &str) -> Result<String, String> {
        let json = std::fs::read_to_string(path).map_err(|e| e.to_string())?;
        let project: Project = serde_json::from_str(&json).map_err(|e| e.to_string())?;

        self.set_current_project(Some(project));
        *self.project_path.lock().unwrap() = Some(PathBuf::from(path));

        Ok(json)
    }

    pub fn get_current_project(&self) -> Result<Option<String>, String> {
        match self.current_project_clone() {
            Some(project) => Ok(Some(
                serde_json::to_string(&project).map_err(|e| e.to_string())?,
            )),
            None => Ok(None),
        }
    }

    pub fn get_project_path(&self) -> Option<String> {
        self.project_path
            .lock()
            .unwrap()
            .as_ref()
            .map(|p| p.display().to_string())
    }

    pub fn update_project(&self, project_json: &str) -> Result<(), String> {
        let project: Project = serde_json::from_str(project_json).map_err(|e| e.to_string())?;
        self.set_current_project(Some(project));
        Ok(())
    }

    pub async fn generate_code(&self, output_dir: &str) -> Result<GenerationReport, String> {
        let project = self.current_project_clone().ok_or("No project loaded")?;

        let generated = nocode_codegen::generate_project(&project, &PathBuf::from(output_dir))
            .await
            .map_err(|e| e.to_string())?;

        Ok(GenerationReport {
            output_dir: output_dir.to_string(),
            backend_files: generated.backend.files.len(),
            frontend_files: generated.frontend.files.len(),
            migrations: generated.database.migrations.len(),
        })
    }

    pub async fn generate_zip(&self) -> Result<Vec<u8>, String> {
        let project = self.current_project_clone().ok_or("No project loaded")?;

        let generated = nocode_codegen::generate_project_in_memory(&project)
            .await
            .map_err(|e| e.to_string())?;

        generated.to_zip().map_err(|e| e.to_string())
    }
}
