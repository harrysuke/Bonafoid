    #[test]
    fn exclusive_gateway_uses_default_flow() {
        let s = start("S");
        let low = end("Low");
        let default_end = end("Default");

        // Build the default edge first so the gateway can reference its id.
        let probe = node(
            "Decision",
            WorkflowNodeType::ExclusiveGateway { default_flow: None },
        );
        let mut e_cond = edge_cond(&probe, &low, Some("amount < 10"));
        let mut e_default = edge(&probe, &default_end);

        // Rebuild the gateway with an explicit default flow id.
        let gw = node(
            "Decision",
            WorkflowNodeType::ExclusiveGateway {
                default_flow: Some(e_default.id.clone()),
            },
        );
        e_cond.source = gw.id.clone();
        e_default.source = gw.id.clone();

        let wf = workflow(
            vec![s.clone(), gw.clone(), low.clone(), default_end.clone()],
            vec![edge(&s, &gw), e_cond, e_default],
        );
        let instance = BpmnEngine::new()
            .start(&wf, vars(&[("amount", serde_json::json!(500))]))
            .unwrap();
        assert!(instance
            .history
            .iter()
            .any(|h| h.node_name.as_deref() == Some("Default")));
    }

