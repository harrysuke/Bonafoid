//! A compact, deterministic BPMN process engine operating on the
//! [`nocode_model::Workflow`] graph.
//!
//! The engine is token based: a [`ProcessInstance`] owns a set of [`Token`]s
//! that flow through the workflow graph. User tasks park their token until
//! they are completed, gateways fan tokens out or select a single path, and
//! the instance completes once every token is consumed.

use chrono::{DateTime, Utc};
use indexmap::IndexMap;
use serde::{Deserialize, Serialize};
use uuid::Uuid;

use nocode_model::{
    EdgeId, NodeId, ServiceTaskImplementation, StartEventType, Workflow, WorkflowId, WorkflowNode,
    WorkflowNodeType,
};

use crate::error::{BpmnError, Result};
use crate::expr;

/// Status of a process instance.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum InstanceStatus {
    Running,
    Completed,
    Failed,
    Terminated,
}

/// Status of an individual token.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum TokenStatus {
    Ready,
    Waiting,
    Consumed,
}

/// Status of a user task.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum TaskStatus {
    Created,
    Claimed,
    Completed,
    Cancelled,
}

/// A unit of execution flowing through the process graph.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Token {
    pub id: String,
    pub node_id: NodeId,
    pub status: TokenStatus,
}

impl Token {
    fn new(node_id: NodeId) -> Self {
        Self {
            id: Uuid::new_v4().to_string(),
            node_id,
            status: TokenStatus::Ready,
        }
    }
}

/// A human task generated by a user task node.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct TaskInstance {
    pub id: String,
    pub token_id: String,
    pub node_id: NodeId,
    pub name: String,
    pub assignee: Option<String>,
    pub candidate_groups: Vec<String>,
    pub form_id: Option<String>,
    pub due_date: Option<String>,
    pub status: TaskStatus,
    pub created_at: DateTime<Utc>,
    pub completed_at: Option<DateTime<Utc>>,
}

/// An audit/history entry recorded during execution.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct HistoryEvent {
    pub timestamp: DateTime<Utc>,
    pub node_id: Option<NodeId>,
    pub node_name: Option<String>,
    pub event_type: String,
    pub detail: Option<String>,
}

/// A live or completed process instance.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ProcessInstance {
    pub id: String,
    pub workflow_id: WorkflowId,
    pub workflow_name: String,
    pub status: InstanceStatus,
    pub tokens: Vec<Token>,
    pub variables: IndexMap<String, serde_json::Value>,
    pub tasks: Vec<TaskInstance>,
    pub history: Vec<HistoryEvent>,
    pub created_at: DateTime<Utc>,
    pub updated_at: DateTime<Utc>,
}

impl ProcessInstance {
    /// Find an open task by id.
    pub fn task(&self, task_id: &str) -> Option<&TaskInstance> {
        self.tasks.iter().find(|t| t.id == task_id)
    }

    /// Whether the instance is still running.
    pub fn is_running(&self) -> bool {
        self.status == InstanceStatus::Running
    }

    /// The ids of all tasks that are still open.
    pub fn open_tasks(&self) -> Vec<&TaskInstance> {
        self.tasks
            .iter()
            .filter(|t| matches!(t.status, TaskStatus::Created | TaskStatus::Claimed))
            .collect()
    }
}

/// A problem discovered while validating a workflow.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ValidationIssue {
    pub severity: Severity,
    pub node_id: Option<String>,
    pub message: String,
}

/// Severity of a validation issue.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Severity {
    Error,
    Warning,
}

/// Outcome of a validation pass.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, Default)]
pub struct ValidationResult {
    pub issues: Vec<ValidationIssue>,
}

impl ValidationResult {
    /// Whether any issue has [`Severity::Error`].
    pub fn is_valid(&self) -> bool {
        !self.issues.iter().any(|i| i.severity == Severity::Error)
    }

    fn error(&mut self, node_id: Option<String>, message: impl Into<String>) {
        self.issues.push(ValidationIssue {
            severity: Severity::Error,
            node_id,
            message: message.into(),
        });
    }

    fn warning(&mut self, node_id: Option<String>, message: impl Into<String>) {
        self.issues.push(ValidationIssue {
            severity: Severity::Warning,
            node_id,
            message: message.into(),
        });
    }
}

/// The BPMN engine. Stateless with respect to instances: methods take the
/// workflow definition and return updated [`ProcessInstance`] values.
#[derive(Debug, Default, Clone)]
pub struct BpmnEngine {
    max_steps: usize,
}

impl BpmnEngine {
    /// Create an engine with a default step budget to guard against infinite
    /// loops in cyclic graphs.
    pub fn new() -> Self {
        Self { max_steps: 100_000 }
    }

    /// Override the maximum number of node executions per `advance` call.
    pub fn with_max_steps(mut self, max_steps: usize) -> Self {
        self.max_steps = max_steps;
        self
    }

    /// Validate the structural integrity of a workflow.
    pub fn validate(&self, workflow: &Workflow) -> ValidationResult {
        let mut result = ValidationResult::default();

        if workflow.nodes.is_empty() {
            result.error(None, "workflow has no nodes");
            return result;
        }

        let ids: Vec<NodeId> = workflow.nodes.iter().map(|n| n.id.clone()).collect();
        let unique: std::collections::HashSet<&NodeId> = ids.iter().collect();
        if unique.len() != ids.len() {
            result.error(None, "workflow contains duplicate node ids");
        }

        let starts: Vec<&WorkflowNode> = workflow
            .nodes
            .iter()
            .filter(|n| matches!(n.node_type, WorkflowNodeType::StartEvent { .. }))
            .collect();
        match starts.len() {
            0 => result.error(None, "workflow must contain exactly one start event"),
            1 => {}
            n => result.error(None, format!("workflow has {n} start events, expected 1")),
        }

        if !workflow
            .nodes
            .iter()
            .any(|n| matches!(n.node_type, WorkflowNodeType::EndEvent { .. }))
        {
            result.warning(None, "workflow has no end event");
        }

        for edge in &workflow.edges {
            if !unique.contains(&edge.source) {
                result.error(
                    Some(edge.source.to_string()),
                    format!(
                        "edge {} references unknown source node {}",
                        edge.id, edge.source
                    ),
                );
            }
            if !unique.contains(&edge.target) {
                result.error(
                    Some(edge.target.to_string()),
                    format!(
                        "edge {} references unknown target node {}",
                        edge.id, edge.target
                    ),
                );
            }
        }

        for node in &workflow.nodes {
            let outgoing: Vec<&nocode_model::WorkflowEdge> = workflow
                .edges
                .iter()
                .filter(|e| e.source == node.id)
                .collect();
            let incoming = workflow
                .edges
                .iter()
                .filter(|e| e.target == node.id)
                .count();

            if !matches!(node.node_type, WorkflowNodeType::EndEvent { .. }) && outgoing.is_empty() {
                result.error(
                    Some(node.id.to_string()),
                    format!("node `{}` has no outgoing flow", node.name),
                );
            }
            if !matches!(node.node_type, WorkflowNodeType::StartEvent { .. }) && incoming == 0 {
                result.error(
                    Some(node.id.to_string()),
                    format!("node `{}` has no incoming flow", node.name),
                );
            }

            if let WorkflowNodeType::ExclusiveGateway { default_flow }
            | WorkflowNodeType::InclusiveGateway { default_flow } = &node.node_type
            {
                let non_default_without_condition = outgoing
                    .iter()
                    .filter(|e| e.condition.is_none() && Some(&e.id) != default_flow.as_ref())
                    .count();
                if outgoing.len() > 1 && non_default_without_condition > 1 {
                    result.warning(
                        Some(node.id.to_string()),
                        "gateway has multiple unconditional outgoing flows; only the first is used",
                    );
                }
            }
        }

        result
    }

    /// Start a new process instance from a workflow.
    pub fn start(
        &self,
        workflow: &Workflow,
        variables: IndexMap<String, serde_json::Value>,
    ) -> Result<ProcessInstance> {
        let validation = self.validate(workflow);
        if !validation.is_valid() {
            let first = validation
                .issues
                .iter()
                .find(|i| i.severity == Severity::Error)
                .map(|i| i.message.clone())
                .unwrap_or_else(|| "invalid workflow".to_string());
            return Err(BpmnError::InvalidWorkflow(first));
        }

        let start = workflow
            .nodes
            .iter()
            .find(|n| matches!(n.node_type, WorkflowNodeType::StartEvent { .. }))
            .ok_or_else(|| BpmnError::InvalidWorkflow("missing start event".into()))?;

        let now = Utc::now();
        let mut instance = ProcessInstance {
            id: Uuid::new_v4().to_string(),
            workflow_id: workflow.id.clone(),
            workflow_name: workflow.name.clone(),
            status: InstanceStatus::Running,
            tokens: vec![Token::new(start.id.clone())],
            variables,
            tasks: Vec::new(),
            history: vec![HistoryEvent {
                timestamp: now,
                node_id: Some(start.id.clone()),
                node_name: Some(start.name.clone()),
                event_type: "instance_started".to_string(),
                detail: None,
            }],
            created_at: now,
            updated_at: now,
        };

        // Apply default variable values from the workflow definition.
        for var in &workflow.variables {
            if let Some(default) = &var.default_value {
                instance
                    .variables
                    .entry(var.name.clone())
                    .or_insert_with(|| default.clone());
            }
        }

        self.advance(workflow, &mut instance)?;
        Ok(instance)
    }

    /// Complete a user task and resume the process.
    pub fn complete_task(
        &self,
        workflow: &Workflow,
        instance: &mut ProcessInstance,
        task_id: &str,
        variables: IndexMap<String, serde_json::Value>,
    ) -> Result<()> {
        if !instance.is_running() {
            return Err(BpmnError::InstanceNotRunning(instance.id.clone()));
        }

        let now = Utc::now();
        let (token_id, node_id) = {
            let task = instance
                .tasks
                .iter_mut()
                .find(|t| t.id == task_id)
                .ok_or_else(|| BpmnError::TaskNotFound(task_id.to_string()))?;
            if task.status == TaskStatus::Completed {
                return Err(BpmnError::TaskAlreadyCompleted(task_id.to_string()));
            }
            task.status = TaskStatus::Completed;
            task.completed_at = Some(now);
            (task.token_id.clone(), task.node_id.clone())
        };

        instance.variables.extend(variables);

        // Move the waiting token past the completed user task and resume.
        if let Some(idx) = instance.tokens.iter().position(|t| t.id == token_id) {
            self.follow_all(workflow, instance, idx, &node_id)?;
        }

        instance.history.push(HistoryEvent {
            timestamp: now,
            node_id: None,
            node_name: None,
            event_type: "task_completed".to_string(),
            detail: Some(task_id.to_string()),
        });

        self.advance(workflow, instance)?;
        Ok(())
    }

    /// Assign a user task to a user.
    pub fn claim_task(
        &self,
        instance: &mut ProcessInstance,
        task_id: &str,
        assignee: &str,
    ) -> Result<()> {
        let task = instance
            .tasks
            .iter_mut()
            .find(|t| t.id == task_id)
            .ok_or_else(|| BpmnError::TaskNotFound(task_id.to_string()))?;
        if task.status != TaskStatus::Created {
            return Err(BpmnError::TaskAlreadyCompleted(task_id.to_string()));
        }
        task.assignee = Some(assignee.to_string());
        task.status = TaskStatus::Claimed;
        Ok(())
    }

    /// Terminate a running instance.
    pub fn terminate(&self, instance: &mut ProcessInstance) {
        for token in &mut instance.tokens {
            token.status = TokenStatus::Consumed;
        }
        for task in &mut instance.tasks {
            if matches!(task.status, TaskStatus::Created | TaskStatus::Claimed) {
                task.status = TaskStatus::Cancelled;
            }
        }
        instance.status = InstanceStatus::Terminated;
        instance.updated_at = Utc::now();
        instance.history.push(HistoryEvent {
            timestamp: instance.updated_at,
            node_id: None,
            node_name: None,
            event_type: "instance_terminated".to_string(),
            detail: None,
        });
    }

    /// Advance all ready tokens until the instance blocks on a user task or
    /// completes.
    fn advance(&self, workflow: &Workflow, instance: &mut ProcessInstance) -> Result<()> {
        let mut steps = 0usize;

        loop {
            steps += 1;
            if steps > self.max_steps {
                return Err(BpmnError::Execution(
                    "maximum step budget exceeded (possible infinite loop)".into(),
                ));
            }

            // Find the first ready token.
            let Some(idx) = instance
                .tokens
                .iter()
                .position(|t| t.status == TokenStatus::Ready)
            else {
                break;
            };

            let token = instance.tokens[idx].clone();
            let node = workflow
                .nodes
                .iter()
                .find(|n| n.id == token.node_id)
                .ok_or_else(|| {
                    BpmnError::Execution(format!("token references missing node {}", token.node_id))
                })?
                .clone();

            self.execute_node(workflow, instance, &token, &node)?;
        }

        // Determine completion: no ready or waiting tokens left.
        let has_live = instance
            .tokens
            .iter()
            .any(|t| matches!(t.status, TokenStatus::Ready | TokenStatus::Waiting));

        if !has_live && instance.status == InstanceStatus::Running {
            instance.status = InstanceStatus::Completed;
            instance.updated_at = Utc::now();
            instance.history.push(HistoryEvent {
                timestamp: instance.updated_at,
                node_id: None,
                node_name: None,
                event_type: "instance_completed".to_string(),
                detail: None,
            });
        }

        Ok(())
    }

    /// Execute a single node for the given token.
    fn execute_node(
        &self,
        workflow: &Workflow,
        instance: &mut ProcessInstance,
        token: &Token,
        node: &WorkflowNode,
    ) -> Result<()> {
        let now = Utc::now();
        let token_idx = instance
            .tokens
            .iter()
            .position(|t| t.id == token.id)
            .expect("token exists");

        // Record that we entered the node.
        instance.history.push(HistoryEvent {
            timestamp: now,
            node_id: Some(node.id.clone()),
            node_name: Some(node.name.clone()),
            event_type: "node_entered".to_string(),
            detail: None,
        });

        match &node.node_type {
            WorkflowNodeType::StartEvent { event_type } => {
                if let StartEventType::Conditional { condition } = event_type {
                    if !expr::evaluate(condition, &instance.variables)? {
                        // Cancel the instance because the start condition is false.
                        instance.tokens[token_idx].status = TokenStatus::Consumed;
                        instance.status = InstanceStatus::Terminated;
                        return Ok(());
                    }
                }
                self.follow_all(workflow, instance, token_idx, &node.id)?;
            }

            WorkflowNodeType::EndEvent { .. } => {
                instance.tokens[token_idx].status = TokenStatus::Consumed;
            }

            WorkflowNodeType::UserTask {
                assignee,
                candidate_groups,
                form_id,
                due_date,
            } => {
                let task = TaskInstance {
                    id: Uuid::new_v4().to_string(),
                    token_id: token.id.clone(),
                    node_id: node.id.clone(),
                    name: node.name.clone(),
                    assignee: assignee.clone(),
                    candidate_groups: candidate_groups.clone(),
                    form_id: form_id.as_ref().map(|f| f.to_string()),
                    due_date: due_date.clone(),
                    status: TaskStatus::Created,
                    created_at: now,
                    completed_at: None,
                };
                instance.tasks.push(task);
                instance.tokens[token_idx].status = TokenStatus::Waiting;
            }

            WorkflowNodeType::ServiceTask { implementation, .. } => {
                let detail = describe_service_task(implementation);
                instance.history.push(HistoryEvent {
                    timestamp: now,
                    node_id: Some(node.id.clone()),
                    node_name: Some(node.name.clone()),
                    event_type: "service_task_executed".to_string(),
                    detail: Some(detail),
                });
                self.follow_all(workflow, instance, token_idx, &node.id)?;
            }

            WorkflowNodeType::ScriptTask { script, .. } => {
                instance.history.push(HistoryEvent {
                    timestamp: now,
                    node_id: Some(node.id.clone()),
                    node_name: Some(node.name.clone()),
                    event_type: "script_task_executed".to_string(),
                    detail: Some(script.clone()),
                });
                self.follow_all(workflow, instance, token_idx, &node.id)?;
            }

            WorkflowNodeType::BusinessRuleTask { decision_ref, .. } => {
                instance.history.push(HistoryEvent {
                    timestamp: now,
                    node_id: Some(node.id.clone()),
                    node_name: Some(node.name.clone()),
                    event_type: "business_rule_evaluated".to_string(),
                    detail: Some(decision_ref.clone()),
                });
                self.follow_all(workflow, instance, token_idx, &node.id)?;
            }

            WorkflowNodeType::SendTask { message_ref }
            | WorkflowNodeType::ReceiveTask { message_ref } => {
                instance.history.push(HistoryEvent {
                    timestamp: now,
                    node_id: Some(node.id.clone()),
                    node_name: Some(node.name.clone()),
                    event_type: "message_task".to_string(),
                    detail: Some(message_ref.clone()),
                });
                self.follow_all(workflow, instance, token_idx, &node.id)?;
            }

            WorkflowNodeType::ManualTask | WorkflowNodeType::Task { .. } => {
                self.follow_all(workflow, instance, token_idx, &node.id)?;
            }

            WorkflowNodeType::ExclusiveGateway { default_flow } => {
                let chosen =
                    self.select_exclusive(workflow, node, instance, default_flow.as_ref())?;
                match chosen {
                    Some(target) => {
                        instance.tokens[token_idx].node_id = target;
                        instance.tokens[token_idx].status = TokenStatus::Ready;
                    }
                    None => {
                        return Err(BpmnError::Execution(format!(
                            "exclusive gateway `{}` has no matching outgoing flow",
                            node.name
                        )));
                    }
                }
            }

            WorkflowNodeType::InclusiveGateway { default_flow } => {
                let targets =
                    self.select_inclusive(workflow, node, instance, default_flow.as_ref())?;
                if targets.is_empty() {
                    return Err(BpmnError::Execution(format!(
                        "inclusive gateway `{}` has no matching outgoing flow",
                        node.name
                    )));
                }
                instance.tokens[token_idx].status = TokenStatus::Consumed;
                for target in targets {
                    instance.tokens.push(Token::new(target));
                }
            }

            WorkflowNodeType::ParallelGateway
            | WorkflowNodeType::EventBasedGateway
            | WorkflowNodeType::SubProcess { .. }
            | WorkflowNodeType::CallActivity { .. } => {
                self.follow_all(workflow, instance, token_idx, &node.id)?;
            }
        }

        Ok(())
    }

    /// Move the token at `token_idx` to every outgoing target.
    fn follow_all(
        &self,
        workflow: &Workflow,
        instance: &mut ProcessInstance,
        token_idx: usize,
        node_id: &NodeId,
    ) -> Result<()> {
        let targets: Vec<NodeId> = workflow
            .edges
            .iter()
            .filter(|e| &e.source == node_id)
            .map(|e| e.target.clone())
            .collect();

        if targets.is_empty() {
            // Dead end: consume the token.
            instance.tokens[token_idx].status = TokenStatus::Consumed;
            return Ok(());
        }

        instance.tokens[token_idx].status = TokenStatus::Consumed;
        for target in targets {
            instance.tokens.push(Token::new(target));
        }
        Ok(())
    }

    /// Select a single outgoing edge for an exclusive gateway.
    fn select_exclusive(
        &self,
        workflow: &Workflow,
        node: &WorkflowNode,
        instance: &ProcessInstance,
        default_flow: Option<&EdgeId>,
    ) -> Result<Option<NodeId>> {
        let outgoing: Vec<&nocode_model::WorkflowEdge> = workflow
            .edges
            .iter()
            .filter(|e| e.source == node.id)
            .collect();

        for edge in &outgoing {
            if let Some(condition) = &edge.condition {
                if expr::evaluate(condition, &instance.variables)? {
                    return Ok(Some(edge.target.clone()));
                }
            }
        }

        if let Some(default_flow) = default_flow {
            if let Some(edge) = outgoing.iter().find(|e| &e.id == default_flow) {
                return Ok(Some(edge.target.clone()));
            }
        }

        // Fall back to the first unconditional flow, if any.
        if let Some(edge) = outgoing.iter().find(|e| e.condition.is_none()) {
            return Ok(Some(edge.target.clone()));
        }

        Ok(None)
    }

    /// Select all matching outgoing edges for an inclusive gateway.
    fn select_inclusive(
        &self,
        workflow: &Workflow,
        node: &WorkflowNode,
        instance: &ProcessInstance,
        default_flow: Option<&EdgeId>,
    ) -> Result<Vec<NodeId>> {
        let outgoing: Vec<&nocode_model::WorkflowEdge> = workflow
            .edges
            .iter()
            .filter(|e| e.source == node.id)
            .collect();

        let mut matched = Vec::new();
        for edge in &outgoing {
            match &edge.condition {
                Some(condition) => {
                    if expr::evaluate(condition, &instance.variables)? {
                        matched.push(edge.target.clone());
                    }
                }
                None => {
                    // Unconditional edges only taken if it's the default or
                    // nothing else matched yet.
                    if default_flow == Some(&edge.id) {
                        matched.push(edge.target.clone());
                    }
                }
            }
        }

        if matched.is_empty() {
            if let Some(default_flow) = default_flow {
                if let Some(edge) = outgoing.iter().find(|e| &e.id == default_flow) {
                    matched.push(edge.target.clone());
                }
            }
        }

        Ok(matched)
    }
}

fn describe_service_task(implementation: &ServiceTaskImplementation) -> String {
    match implementation {
        ServiceTaskImplementation::Http { url, method, .. } => {
            format!("http {method:?} {url}")
        }
        ServiceTaskImplementation::Function { function_name, .. } => {
            format!("function {function_name}")
        }
        ServiceTaskImplementation::Plugin { plugin_id, .. } => format!("plugin {plugin_id}"),
        ServiceTaskImplementation::External {
            connector_id,
            operation,
            ..
        } => format!("external {connector_id}.{operation}"),
    }
}

